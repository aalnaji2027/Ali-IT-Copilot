import re

from ollama import Client


DEFAULT_MODEL = "llama3.2:3b"
DEFAULT_HOST = "http://localhost:11434"


SYSTEM_PROMPT = """
You are Ali IT Copilot, a private local AI assistant.

Use the supplied knowledge context only when it is relevant to the
user's question.

Rules:
1. Base document-related answers on the supplied knowledge context.
2. Do not invent facts that are absent from the supplied context.
3. If the context is insufficient, clearly state that the indexed
   knowledge does not contain enough information.
4. Do not use irrelevant knowledge merely because it was supplied.
5. Keep answers clear, practical, and concise.
6. Reply in the same language used in the latest user question.
7. If the latest user question contains Arabic, answer entirely
   in Arabic.
8. Do not create a references, citations, sources, or knowledge
   sources section.
9. Do not add document citations at the end of the answer.
10. The application will append verified source citations separately.
""".strip()


def get_client():
    """Create a client connected to the local Ollama service."""

    return Client(
        host=DEFAULT_HOST
    )


def check_local_ai():
    """Check the Ollama connection and model availability."""

    try:
        client = get_client()
        response = client.list()

        model_names = []

        for model in response.models:
            model_name = (
                getattr(model, "model", None)
                or getattr(model, "name", None)
                or ""
            )

            if model_name:
                model_names.append(
                    model_name
                )

        model_available = any(
            model_name == DEFAULT_MODEL
            for model_name in model_names
        )

        return {
            "connected": True,
            "model_available": model_available,
            "model": DEFAULT_MODEL,
            "models": model_names,
            "error": "",
        }

    except Exception as error:
        return {
            "connected": False,
            "model_available": False,
            "model": DEFAULT_MODEL,
            "models": [],
            "error": str(error),
        }


def contains_arabic(text):
    """Return True when the text contains Arabic characters."""

    return bool(
        re.search(
            r"[\u0600-\u06FF]",
            text or "",
        )
    )


def remove_model_source_section(response_text):
    """
    Remove source sections generated by the model.

    Verified citations are added separately by main.py.
    """

    if not response_text:
        return ""

    source_heading_pattern = re.compile(
        (
            r"\n\s*"
            r"(?:"
            r"\*{0,2}knowledge\s+sources\*{0,2}"
            r"|\*{0,2}sources\*{0,2}"
            r"|\*{0,2}references\*{0,2}"
            r"|\*{0,2}المصادر\*{0,2}"
            r"|\*{0,2}مصادر\s+المعرفة\*{0,2}"
            r")"
            r"\s*:"
        ),
        flags=re.IGNORECASE,
    )

    match = source_heading_pattern.search(
        response_text
    )

    if match:
        response_text = response_text[
            :match.start()
        ]

    return response_text.strip()


def build_knowledge_context(
    knowledge_results,
):
    """Convert retrieved chunks into grounded model context."""

    if not knowledge_results:
        return (
            "No matching indexed knowledge passages "
            "were retrieved."
        )

    context_sections = []

    for result_number, result in enumerate(
        knowledge_results,
        start=1,
    ):
        context_sections.append(
            "\n".join(
                [
                    f"[Source {result_number}]",
                    (
                        "Document: "
                        f"{result['file_name']}"
                    ),
                    (
                        "Chunk: "
                        f"{result['sequence_number']}"
                    ),
                    "Content:",
                    result["content"],
                ]
            )
        )

    return "\n\n".join(
        context_sections
    )


def build_language_instruction(
    user_message,
):
    """Build an explicit instruction for the user's language."""

    if contains_arabic(user_message):
        return (
            "The latest user question is written in Arabic. "
            "Answer entirely in Arabic. Do not answer in English."
        )

    return (
        "Answer in the same language used in the latest "
        "user question."
    )


def generate_local_response(
    user_message,
    knowledge_results=None,
    conversation_history=None,
):
    """Generate a local, knowledge-grounded answer."""

    knowledge_results = (
        knowledge_results or []
    )

    conversation_history = (
        conversation_history or []
    )

    knowledge_context = build_knowledge_context(
        knowledge_results
    )

    language_instruction = (
        build_language_instruction(
            user_message
        )
    )

    messages = [
        {
            "role": "system",
            "content": SYSTEM_PROMPT,
        }
    ]

    for history_item in conversation_history[-6:]:

        history_user = history_item.get(
            "user",
            "",
        ).strip()

        history_assistant = history_item.get(
            "assistant",
            "",
        ).strip()

        if history_user:
            messages.append(
                {
                    "role": "user",
                    "content": history_user,
                }
            )

        if history_assistant:
            messages.append(
                {
                    "role": "assistant",
                    "content": history_assistant,
                }
            )

    grounded_prompt = f"""
Knowledge context:

{knowledge_context}

Latest user question:

{user_message}

Instructions:

{language_instruction}

Use the knowledge context only when it directly helps answer the
latest question.

If no relevant indexed knowledge was retrieved, do not claim that
the available documents contain information about the question.

Do not write a sources, references, citations, or knowledge sources
section. The application adds verified citations separately.
""".strip()

    messages.append(
        {
            "role": "user",
            "content": grounded_prompt,
        }
    )

    try:
        client = get_client()

        response = client.chat(
            model=DEFAULT_MODEL,
            messages=messages,
            options={
                "temperature": 0.2,
                "num_ctx": 8192,
            },
        )

        response_text = (
            response.message.content.strip()
        )

        response_text = remove_model_source_section(
            response_text
        )

        if not response_text:
            raise ValueError(
                "The local model returned an empty response."
            )

        sources = []
        seen_sources = set()

        for result in knowledge_results:
            source_key = (
                result["file_name"],
                result["sequence_number"],
            )

            if source_key in seen_sources:
                continue

            seen_sources.add(
                source_key
            )

            sources.append(
                {
                    "file_name": result[
                        "file_name"
                    ],
                    "sequence_number": result[
                        "sequence_number"
                    ],
                }
            )

        return {
            "success": True,
            "response": response_text,
            "model": DEFAULT_MODEL,
            "sources": sources,
            "error": "",
        }

    except Exception as error:
        return {
            "success": False,
            "response": "",
            "model": DEFAULT_MODEL,
            "sources": [],
            "error": str(error),
        }